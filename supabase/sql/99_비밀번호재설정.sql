-- 비밀번호 재설정 (어드민이 잠겼을 때의 비상구)
-- ------------------------------------------------------------
-- 수파베이스 → SQL Editor 에 붙여넣고,
-- 아래 두 군데의 ★ 표시만 고친 뒤 RUN 하세요.
--
--   ① 아이디        : 'kmj'            ← 바꿀 계정
--   ② 새 비밀번호   : '여기에새비밀번호'  ← 4자 이상
--
-- ※ 아이디가 두 군데(해시 계산식 안, where 절) 모두 들어갑니다.
--    서로 다르면 로그인이 안 되니 똑같이 맞춰주세요.
-- ============================================================

create extension if not exists pgcrypto;

update partner."사용자"
set "비번해시" = translate(
      encode(
        digest('wnet-2026-8f3a9c1e-partner-secret' || '|' ||
               'kmj'              /* ★① 아이디 */      || '|' ||
               '여기에새비밀번호'  /* ★② 새 비밀번호 */ , 'sha256'),
        'base64'),
      '+/', '-_')
where "아이디" = 'kmj';     -- ★① 아이디 (위와 똑같이)

-- 확인 — 1 row 가 바뀌었는지, 계정이 살아있는지 보세요
select "아이디", "이름", "권한", "상태" from partner."사용자" where "아이디" = 'kmj';

