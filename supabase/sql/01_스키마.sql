-- ------------------------------------------------------------
create table if not exists partner."변경로그" (
  "id"      bigint generated by default as identity primary key,
  "일시"    timestamptz not null default now(),
  "아이디"  text,
  "이름"    text,
  "작업"    text not null,
  "대상"    text,
  "상세"    text
