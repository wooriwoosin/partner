create schema if not exists partner;

-- ------------------------------------------------------------
-- 업체 — 메인 테이블 (구글시트 '업체관리' 탭을 대체)
-- ------------------------------------------------------------
create table if not exists partner."업체" (
  "id"           bigint generated by default as identity primary key,

  -- 식별
  "업체명"        text not null,
  "소속원문"      text not null unique,        -- 중복 등록 방지: DB 가 거부한다
  "기호"          text,
  "업체구분"      text not null check ("업체구분" in ('판매점', '협력점', '자점')),
  "인센티브"      text check ("인센티브" in ('Y', 'N')),
  "전달마커"      text check ("전달마커" in ('O', 'X', '?')),
  "상태"          text not null default '활성' check ("상태" in ('활성', '휴면')),

  -- 기본 정보
  "소통채널"      text,
  "웹접수"        text check ("웹접수" in ('Y', 'N')),
  "웹회신"        text check ("웹회신" in ('Y', 'N')),
  "대표자"        text,
  "연락처"        text,
  "계정수"        integer check ("계정수" >= 0),
  "비고"          text,

  -- 계산서
  "법인"          text,
  "계산서형태"    text check ("계산서형태" in ('정발행', '역발행', '원천세', '기타')),
  "수신방법"      text,
  "사업자등록증"  text check ("사업자등록증" in ('Y', 'N')),
  "계산서비고"    text,

  -- 계약서·보증보험
  "위탁판매"      text check ("위탁판매" in ('Y', 'N')),
  "개인정보"      text check ("개인정보" in ('Y', 'N')),
  "보증보험"      text check ("보증보험" in ('Y', 'N')),
  "계약제외"      text check ("계약제외" in ('Y', 'N')),
  "계약비고"      text,
  "계약서발송"    text check ("계약서발송" in ('Y', 'N')),

  -- 관리
  "출처"          text,
  "등록일"        date,
  "최근개통일"    date,
  "수정일시"      timestamptz not null default now()
);

comment on table  partner."업체"       is '업체 마스터. 자점은 저장만 하고 앱 화면에는 노출하지 않는다.';
comment on column partner."업체"."소속원문"   is '기호 포함 원문. 개통리스트 매칭 기준이라 유니크로 중복 등록을 막는다.';
comment on column partner."업체"."위탁판매"   is 'Y/N. 빈칸(NULL)은 "아직 확인 안 함", N 은 "확인했고 아님" — 서로 다르다.';

create index if not exists "업체_업체구분_idx"   on partner."업체" ("업체구분");
create index if not exists "업체_상태_idx"       on partner."업체" ("상태");
create index if not exists "업체_최근개통일_idx" on partner."업체" ("최근개통일" desc);
create index if not exists "업체_업체명_idx"     on partner."업체" ("업체명");

