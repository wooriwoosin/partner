create index if not exists "변경로그_일시_idx" on partner."변경로그" ("일시" desc);

-- ============================================================
-- 트리거
-- ============================================================

-- 빈 문자열('')을 NULL 로 통일한다.
-- 빈칸이 두 종류('' 와 NULL)로 갈리면 "정보없음" 판정이 어긋나기 때문.
create or replace function partner."빈문자열을_NULL로"()
returns trigger
language plpgsql
as $$
declare
  j jsonb;
begin
  select jsonb_object_agg(key, case when value = '""'::jsonb then 'null'::jsonb else value end)
    into j
    from jsonb_each(to_jsonb(NEW));
  NEW := jsonb_populate_record(NEW, j);
  return NEW;
end;
$$;

-- 저장할 때마다 수정일시를 자동으로 찍는다 (앱이 보내주지 않아도 된다)
create or replace function partner."수정일시_갱신"()
returns trigger
language plpgsql
as $$
begin
  NEW."수정일시" := now();
  return NEW;
end;
$$;

-- 변경 내용을 변경로그에 자동 기록.
-- 누가 했는지는 Edge Function 이 app.user_id / app.user_name 으로 알려준다.
create or replace function partner."변경로그_기록"()
returns trigger
language plpgsql
as $$
declare
  작업명   text;
  대상명   text;
  상세내용 text := '';
  키       text;
  이전     jsonb;
  이후     jsonb;
begin
  if TG_OP = 'INSERT' then
    작업명   := '신규등록';
    대상명   := NEW."업체명";
    상세내용 := '소속: ' || coalesce(NEW."소속원문", '') || ' · 구분: ' || coalesce(NEW."업체구분", '');

  elsif TG_OP = 'DELETE' then
    작업명   := '삭제';
    대상명   := OLD."업체명";
    상세내용 := '소속: ' || coalesce(OLD."소속원문", '');

  else
    작업명 := '수정';
    대상명 := NEW."업체명";
    이전   := to_jsonb(OLD);
    이후   := to_jsonb(NEW);
    for 키 in select jsonb_object_keys(이후) loop
      if 키 in ('수정일시', 'id') then continue; end if;
      if (이전 -> 키) is distinct from (이후 -> 키) then
        상세내용 := 상세내용
          || case when 상세내용 = '' then '' else ' | ' end
          || 키 || ': ' || coalesce(이전 ->> 키, '(없음)') || ' → ' || coalesce(이후 ->> 키, '(없음)');
      end if;
    end loop;
    -- 실제로 바뀐 게 없으면 로그를 남기지 않는다
    if 상세내용 = '' then
      return NEW;
    end if;
  end if;

  insert into partner."변경로그" ("아이디", "이름", "작업", "대상", "상세")
  values (
    nullif(current_setting('app.user_id',   true), ''),
    nullif(current_setting('app.user_name', true), ''),
    작업명, 대상명, 상세내용
  );

  if TG_OP = 'DELETE' then return OLD; end if;
  return NEW;
end;
$$;

drop trigger if exists "업체_빈문자열_정리"  on partner."업체";
drop trigger if exists "업체_수정일시"       on partner."업체";
drop trigger if exists "업체_변경로그"       on partner."업체";

create trigger "업체_빈문자열_정리"
  before insert or update on partner."업체"
  for each row execute function partner."빈문자열을_NULL로"();

create trigger "업체_수정일시"
  before insert or update on partner."업체"
  for each row execute function partner."수정일시_갱신"();

create trigger "업체_변경로그"
  after insert or update or delete on partner."업체"
  for each row execute function partner."변경로그_기록"();

